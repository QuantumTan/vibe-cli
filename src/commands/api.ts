import path from 'path';
import fs from 'fs-extra';
import * as p from '@clack/prompts';
import pc from 'picocolors';
import { buildCodebaseMap, ApiRoute } from './map.js';

export interface OpenApiSpec {
  openapi: string;
  info: {
    title: string;
    version: string;
    description: string;
  };
  servers: Array<{ url: string; description: string }>;
  paths: Record<string, Record<string, any>>;
}

/**
 * Normalizes an API path for OpenAPI (e.g. /users/:id -> /users/{id})
 */
export function normalizeOpenApiPath(rawPath: string): { path: string; pathParams: string[] } {
  const pathParams: string[] = [];
  const normalized = rawPath.replace(/:([a-zA-Z0-9_]+)/g, (_, param) => {
    pathParams.push(param);
    return `{${param}}`;
  });

  return { path: normalized, pathParams };
}

/**
 * Builds standard OpenAPI 3.0.3 JSON schema from extracted routes.
 */
export function buildOpenApiSpec(projectName: string, routes: ApiRoute[]): OpenApiSpec {
  const paths: Record<string, Record<string, any>> = {};

  for (const r of routes) {
    const { path: openApiPath, pathParams } = normalizeOpenApiPath(r.path);

    if (!paths[openApiPath]) {
      paths[openApiPath] = {};
    }

    const methodLower = r.method.toLowerCase();
    const tag = openApiPath.split('/')[2] || 'default';

    const parameters = pathParams.map((p) => ({
      name: p,
      in: 'path',
      required: true,
      schema: { type: 'string' },
      description: `Identifier for ${p}`,
    }));

    const operation: Record<string, any> = {
      tags: [tag],
      summary: `${r.method} ${openApiPath}`,
      description: `Handled by \`${r.handler}\``,
      parameters,
      responses: {
        '200': {
          description: 'Successful operation',
          content: {
            'application/json': {
              schema: {
                type: 'object',
                properties: {
                  success: { type: 'boolean' },
                  data: { type: 'object' },
                },
              },
            },
          },
        },
        '400': { description: 'Bad Request / Invalid Parameters' },
        '500': { description: 'Internal Server Error' },
      },
    };

    if (r.method === 'POST' || r.method === 'PUT' || r.method === 'PATCH') {
      operation.requestBody = {
        required: true,
        content: {
          'application/json': {
            schema: {
              type: 'object',
              example: { name: 'sample', active: true },
            },
          },
        },
      };
    }

    paths[openApiPath][methodLower] = operation;
  }

  return {
    openapi: '3.0.3',
    info: {
      title: `${projectName} API`,
      version: '1.0.0',
      description: `Auto-generated OpenAPI 3.0 specification discovered by vibe-cli.`,
    },
    servers: [
      { url: 'http://localhost:3000', description: 'Local Development Server' },
      { url: 'http://localhost:4000', description: 'vibe mock API Server' },
    ],
    paths,
  };
}

/**
 * Generates rich API Reference Markdown documentation with curl examples.
 */
export function formatApiReferenceMarkdown(projectName: string, routes: ApiRoute[]): string {
  const dateStr = new Date().toISOString().substring(0, 10);

  const routeDocs = routes
    .map((r) => {
      const { path: normPath } = normalizeOpenApiPath(r.path);
      const curlCmd =
        r.method === 'GET'
          ? `curl -X GET "http://localhost:3000${normPath}" -H "Accept: application/json"`
          : `curl -X ${r.method} "http://localhost:3000${normPath}" \\\n  -H "Content-Type: application/json" \\\n  -d '{"exampleKey": "exampleValue"}'`;

      return `### \`${r.method}\` \`${normPath}\`\n\n` +
        `> Handler: \`${r.handler}\`\n\n` +
        `#### Example Request\n\`\`\`bash\n${curlCmd}\n\`\`\`\n\n` +
        `#### Responses\n` +
        `- \`200 OK\`: Standard JSON success payload\n` +
        `- \`400 Bad Request\`: Invalid request schema or missing parameters\n` +
        `- \`500 Error\`: Unhandled server exception\n`;
    })
    .join('\n---\n\n');

  return `# API Reference & Endpoint Catalog: ${projectName}

> **Discovered Endpoints**: ${routes.length} • **Format**: OpenAPI 3.0.3 Compatible • **Updated**: ${dateStr}

---

${routeDocs || '*No HTTP API routes detected in workspace.*'}

---
*Auto-generated by \`vibe api\`. Ready to import into Postman, Swagger UI, or client SDK generators.*
`;
}

/**
 * vibe api [options]
 */
export async function apiCommand(
  targetDirInput?: string,
  options: { out?: string; jsonOnly?: boolean } = {}
): Promise<void> {
  const cwd = targetDirInput ? path.resolve(targetDirInput) : process.cwd();
  const projectName = path.basename(cwd);

  p.intro(pc.bgCyan(pc.black(' vibe api ')) + ' ' + pc.bold('OpenAPI 3.0 Exporter & API Documentation'));

  const s = p.spinner();
  s.start(`Discovering API routes across codebase and synthesizing OpenAPI spec...`);

  const map = await buildCodebaseMap(cwd);

  if (map.routes.length === 0) {
    s.stop(pc.yellow('No API routes detected in codebase.'));
    p.log.warn('Searched for Express, Next.js route.ts, FastAPI, and Flask route handlers.');
    p.outro('API exporter idle.');
    return;
  }

  const spec = buildOpenApiSpec(projectName, map.routes);

  // Write openapi.json
  const defaultOutPath = options.out ? path.resolve(options.out) : path.join(cwd, 'openapi.json');
  await fs.writeJSON(defaultOutPath, spec, { spaces: 2 });

  // Write .vault/Architecture/API-Reference.md
  const vaultArchDir = path.join(cwd, '.vault', 'Architecture');
  const targetDir = (await fs.pathExists(path.join(cwd, '.vault'))) ? vaultArchDir : path.join(cwd, 'docs');
  await fs.ensureDir(targetDir);

  const mdOutPath = path.join(targetDir, 'API-Reference.md');
  const mdContent = formatApiReferenceMarkdown(projectName, map.routes);
  await fs.writeFile(mdOutPath, mdContent, 'utf8');

  // Register in 00-Symbol-Index.md
  const symbolIndexFile = path.join(targetDir, '00-Symbol-Index.md');
  if (await fs.pathExists(symbolIndexFile)) {
    const existingIndex = await fs.readFile(symbolIndexFile, 'utf8');
    if (!existingIndex.includes('API-Reference.md')) {
      const appended = existingIndex + `\n- [[API-Reference|🌐 Complete OpenAPI Reference & cURL Catalog]]\n`;
      await fs.writeFile(symbolIndexFile, appended, 'utf8');
    }
  }

  s.stop(pc.green(`Exported ${map.routes.length} endpoints to OpenAPI 3.0!`));

  p.note(
    `Endpoints Found: ${pc.bold(pc.green(map.routes.length.toString()))} route(s)\n` +
      `OpenAPI JSON:    ${pc.white(defaultOutPath)}\n` +
      `API Markdown:    ${pc.white(mdOutPath)}\n\n` +
      `Includes interactive cURL examples, request schemas, and path parameters!`,
    'OpenAPI Export Complete'
  );

  p.outro('Ready to import into Postman, Swagger UI, or feed to frontend developers!');
}
