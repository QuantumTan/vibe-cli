import fs from 'fs-extra';
import path from 'path';
import matter from 'gray-matter';
import type { ProjectMetadata, RegisteredProject } from './types.js';

export function getPlatformSpecificInstructions(category: string, stack: string[]): string {
  const isMobile = category === 'Mobile App' || stack.includes('Flutter') || stack.includes('React Native');
  const isDesktop = category === 'Desktop App' || stack.includes('WPF') || stack.includes('WinForms') || stack.includes('Electron');
  const isBackend = category === 'Backend / API' || stack.includes('Express') || stack.includes('NestJS') || stack.includes('FastAPI') || stack.includes('Laravel');

  if (isMobile) {
    return `### Mobile Development Directives (Android & iOS)
- **Responsive Layout**: Never hardcode physical screen dimensions. Use \`LayoutBuilder\`, \`MediaQuery\`, or adaptive layout components.
- **Touch & Accessibility**: Ensure all interactive touch targets are at least 48x48dp. Provide accessibility labels for screen readers.
- **State & Lifecycle**: Handle app backgrounding, orientation shifts, and network reconnections gracefully.
- **Verification**: Run \`vibe check\` (\`flutter analyze\` or equivalent) before committing any changes.`;
  }

  if (isDesktop) {
    return `### Desktop Application Directives (.NET / Desktop)
- **Architecture**: Follow clean architecture and MVVM patterns. Keep presentation decoupled from core business logic.
- **Resource Management**: Properly dispose unmanaged handles and \`IDisposable\` resources to prevent memory leaks.
- **DPI Awareness**: Ensure UI elements and vector assets scale cleanly across high-DPI and multi-monitor setups.
- **Verification**: Run \`vibe check\` (\`dotnet build\` or equivalent) before finalizing changes.`;
  }

  if (isBackend) {
    return `### Backend & API Directives
- **Schema Validation**: Validate and sanitize all incoming payloads before processing.
- **Database Hygiene**: Never perform destructive schema alterations directly; always use versioned migrations.
- **Security & Secrets**: Never log sensitive user credentials, tokens, or private keys. Rely on environment variables.
- **Verification**: Run \`vibe check\` before completing tasks.`;
  }

  return `### Modern Web Application Directives
- **Responsive Design**: Mobile-first design principles. Ensure fluid layouts across mobile, tablet, and desktop viewports.
- **Accessibility & Contrast**: Adhere to WCAG standards with high-contrast text and keyboard navigability.
- **Performance**: Maintain minimal bundle sizes, lazy-load heavy components, and ensure fast Core Web Vitals.
- **Verification**: Run \`vibe check\` (\`npm run build\` or equivalent) before finalizing changes.`;
}

export function generateProjectAgentsMd(meta: ProjectMetadata): string {
  const platformRules = getPlatformSpecificInstructions(meta.category, meta.stack);

  return `# Agent Guidelines & Memory Sync for ${meta.name}

> Auto-generated by **vibe-cli**. This codebase is permanently wired to Obsidian via live NTFS Directory Junctions.

## 1. Live Obsidian Context & Memory Hub
- **Project Context Hub**: \`.vault/_Context.md\` (Active tasks, sliding window objectives, architecture decisions).
- **Lessons & Gotchas**: \`.vault/Memory-Bank/Lessons-and-Gotchas.md\` (Historical learnings, tricky bugs, and pitfalls).
- **Symbol Index**: \`.vault/Architecture/00-Symbol-Index.md\` (Key components, classes, and endpoints).
- **Global Coding Standards**: \`.vault-global/AGENTS.md\` (System-wide engineering rules).

## 2. Mandatory Memory Sync Rules for AI Agents
Because \`.vault/\` is an NTFS junction directly pointing into Obsidian, **any edit you make here instantly updates Obsidian in real-time**:

1. **At Task Start**:
   - Read \`.vault/_Context.md\` to understand the current objective and active tasks before generating code.
2. **When Solving Tricky Bugs or Making Key Decisions**:
   - Automatically append an entry to \`.vault/Memory-Bank/Lessons-and-Gotchas.md\` so future prompts remember what was learned.
3. **When Adding New Components or Endpoints**:
   - Record the symbol in \`.vault/Architecture/00-Symbol-Index.md\`.
4. **At Task Completion**:
   - Mark completed tasks \`- [x]\` in \`.vault/_Context.md\` and update the \`updatedAt\` timestamp.
   - **Strict Line Limit**: Keep \`.vault/_Context.md\` under 60 lines. Move older completed tasks to \`.vault/Memory-Bank/Archive.md\` (or tell the user to run \`vibe wrapup\`).
5. **Always Verify**:
   - Run verification using: \`${meta.verifyCmd}\` (or \`vibe check\`).

${platformRules}
`;
}

export function generateContextMd(meta: ProjectMetadata, vaultName: string, showcase = false): string {
  const frontmatter = {
    title: meta.name,
    vault: vaultName,
    stack: meta.stack,
    category: meta.category,
    showcase: showcase,
    status: 'Active',
    summary: meta.summary,
    repoUrl: meta.repoUrl || '',
    liveUrl: '',
    updatedAt: new Date().toISOString(),
  };

  const body = `
# ${meta.name}

> ${meta.summary}

## Current Objective
- Project initialized and active in ${vaultName}.

## Active Tasks (Sliding Window)
- [ ] Initial project setup and context configuration
- [ ] Implement core features and verification

## Key Architectural Decisions
- **Tech Stack**: ${meta.stack.join(', ')}
- **Category**: ${meta.category}
- **Verification**: \`${meta.verifyCmd}\`
${meta.devCmd ? `- **Dev Command**: \`${meta.devCmd}\`\n` : ''}`;

  return matter.stringify(body.trim(), frontmatter);
}

export function updateVaultDashboard(vaultPath: string, projects: RegisteredProject[]): void {
  const dashboardPath = path.join(vaultPath, '00-Dashboard.md');
  fs.ensureDirSync(vaultPath);

  let header = `# Obsidian Vault Dashboard\n\nWelcome to your central orchestration hub.\n\n`;
  if (fs.existsSync(dashboardPath)) {
    const existing = fs.readFileSync(dashboardPath, 'utf-8');
    const tableIndex = existing.indexOf('## Active Projects');
    if (tableIndex > 0) {
      header = existing.substring(0, tableIndex);
    }
  }

  let table = `## Active Projects\n\n| Project | Status | Tech Stack | Category | Context Note |\n| :--- | :--- | :--- | :--- | :--- |\n`;

  if (projects.length === 0) {
    table += `| *(No projects linked yet)* | - | - | - | - |\n`;
  } else {
    for (const p of projects) {
      const link = `[[02-Projects/${p.name}/_Context|${p.name}]]`;
      const stackStr = p.stack.join(', ');
      table += `| **${p.name}** | Active | ${stackStr} | ${p.category} | ${link} |\n`;
    }
  }

  fs.writeFileSync(dashboardPath, header.trim() + '\n\n' + table.trim() + '\n', 'utf-8');
}

export function updateVaultAgentsRules(vaultPath: string, projects: RegisteredProject[]): void {
  const globalRulesDir = path.join(vaultPath, '00-Global-Rules');
  const agentsPath = path.join(globalRulesDir, 'AGENTS.md');
  fs.ensureDirSync(globalRulesDir);

  let header = `# Global AI Engineering & Coding Rules

These rules apply across all repositories and sub-projects linked to this Obsidian Vault.

## Universal Principles
1. **Self-Documenting Code**: Code must be readable, modular, and maintain documentation integrity.
2. **Verification First**: Never consider a task complete without running the verification command.
3. **Context Preservation**: Update the respective \`.vault/_Context.md\` whenever architectural decisions shift.
4. **Anti-Slop Directives**: No superfluous boilerplate comments, no hallucinated imports, no breaking changes without migration notes.

`;

  if (fs.existsSync(agentsPath)) {
    const existing = fs.readFileSync(agentsPath, 'utf-8');
    const tableIndex = existing.indexOf('## Registered Projects');
    if (tableIndex > 0) {
      header = existing.substring(0, tableIndex);
    }
  }

  let table = `## Registered Projects\n\n| Project | Tech Stack | Category | Location | Context Note |\n| :--- | :--- | :--- | :--- | :--- |\n`;

  if (projects.length === 0) {
    table += `| *(None registered)* | - | - | - | - |\n`;
  } else {
    for (const p of projects) {
      const link = `[[02-Projects/${p.name}/_Context|${p.name}]]`;
      const stackStr = p.stack.join(', ');
      table += `| **${p.name}** | ${stackStr} | ${p.category} | \`${p.path}\` | ${link} |\n`;
    }
  }

  fs.writeFileSync(agentsPath, header.trim() + '\n\n' + table.trim() + '\n', 'utf-8');
}

export function scaffoldVaultProject(
  vaultPath: string,
  meta: ProjectMetadata,
  vaultName: string,
  showcase = false,
  force = false
): string {
  const projectVaultDir = path.join(vaultPath, '02-Projects', meta.name);
  fs.ensureDirSync(projectVaultDir);

  const contextPath = path.join(projectVaultDir, '_Context.md');
  if (!fs.existsSync(contextPath) || force) {
    const content = generateContextMd(meta, vaultName, showcase);
    fs.writeFileSync(contextPath, content, 'utf-8');
  }

  // Supporting files
  const archDir = path.join(projectVaultDir, 'Architecture');
  const memoryDir = path.join(projectVaultDir, 'Memory-Bank');
  const specsDir = path.join(projectVaultDir, 'Specs');
  fs.ensureDirSync(archDir);
  fs.ensureDirSync(memoryDir);
  fs.ensureDirSync(specsDir);

  const symbolIndexPath = path.join(archDir, '00-Symbol-Index.md');
  if (!fs.existsSync(symbolIndexPath) || force) {
    fs.writeFileSync(
      symbolIndexPath,
      `# Symbol Index for ${meta.name}\n\nIndex of primary classes, components, models, and API endpoints.\n\n- (Populate as codebase evolves)\n`,
      'utf-8'
    );
  }

  const lessonsPath = path.join(memoryDir, 'Lessons-and-Gotchas.md');
  if (!fs.existsSync(lessonsPath) || force) {
    fs.writeFileSync(
      lessonsPath,
      `# Lessons and Gotchas: ${meta.name}\n\nDocument critical edge cases, subtle bugs, and lessons learned here.\n\n- [${new Date().toLocaleDateString()}] Initialized project memory bank.\n`,
      'utf-8'
    );
  }

  const archivePath = path.join(memoryDir, 'Archive.md');
  if (!fs.existsSync(archivePath) || force) {
    fs.writeFileSync(
      archivePath,
      `# Task Archive: ${meta.name}\n\nCompleted tasks from _Context.md are archived here.\n\n`,
      'utf-8'
    );
  }

  const monetizationSpec = path.join(specsDir, 'Monetization-and-Roadmap.md');
  if (!fs.existsSync(monetizationSpec) || force) {
    fs.writeFileSync(
      monetizationSpec,
      `# Monetization & Product Roadmap: ${meta.name}

## 1. Commercial Value Proposition
- **Target Audience**: Who will pay for this or use it every day?
- **Core Value Driver**: What critical problem does this solve faster/better than existing tools?

## 2. Monetization Strategy
- **Pricing Model**: [SaaS Subscription / One-time License / Usage-based / Freemium]
- **Tiers**:
  - **Free Tier**: Essential capabilities for discovery and onboarding.
  - **Pro Tier ($19/mo or $99 lifetime)**: Unlocks full automation, power features, and priority support.
  - **Enterprise**: Custom integrations, teams, and SLA.

## 3. Launch Roadmap (MVP to Profit)
- [ ] Phase 1: Core utility validation & feedback
- [ ] Phase 2: Auth & Stripe / Lemon Squeezy billing integration
- [ ] Phase 3: Telemetry, SEO landing page, and social proof
- [ ] Phase 4: Public launch (Product Hunt, Reddit, Twitter/X)
`,
      'utf-8'
    );
  }

  const qualityChecklist = path.join(specsDir, 'Quality-Checklist.md');
  if (!fs.existsSync(qualityChecklist) || force) {
    fs.writeFileSync(
      qualityChecklist,
      `# Production Quality & Anti-Slop Checklist: ${meta.name}

## 1. UI/UX Polish
- [ ] High-contrast, WCAG-compliant color palette
- [ ] Mobile-responsive layout (no horizontal scrollbugs)
- [ ] Fast Core Web Vitals (< 1.5s LCP) & custom favicon
- [ ] Non-blocking loading states & friendly empty states

## 2. Defensive Engineering & Security
- [ ] .env credentials strictly excluded from Git
- [ ] Graceful error boundaries preventing blank white screen crashes
- [ ] Input validation on every client and API boundary
- [ ] Zero build warnings on \`${meta.verifyCmd}\`

## 3. Commercial Readiness
- [ ] Functional checkout / payment webhook
- [ ] Error tracking (Sentry) and user analytics (PostHog) configured
`,
      'utf-8'
    );
  }

  const gitkeepPath = path.join(specsDir, '.gitkeep');
  if (!fs.existsSync(gitkeepPath)) {
    fs.writeFileSync(gitkeepPath, '', 'utf-8');
  }

  // Platform specific spec files
  if (meta.category === 'Mobile App' || meta.stack.includes('Flutter')) {
    const mobileSpec = path.join(specsDir, 'Platform-Notes.md');
    if (!fs.existsSync(mobileSpec) || force) {
      fs.writeFileSync(
        mobileSpec,
        `# Mobile Platform Notes for ${meta.name}\n\n- **Target Platforms**: Android, iOS\n- **Framework**: ${meta.stack.join(', ')}\n- **Package / Identifier**: ${meta.platformNotes?.flutterPackage || 'Auto-detected'}\n`,
        'utf-8'
      );
    }
  }

  if (meta.category === 'Desktop App' || meta.stack.includes('WPF') || meta.stack.includes('WinForms')) {
    const desktopSpec = path.join(specsDir, 'Architecture.md');
    if (!fs.existsSync(desktopSpec) || force) {
      fs.writeFileSync(
        desktopSpec,
        `# Desktop Architecture Notes for ${meta.name}\n\n- **Target Platform**: Windows (x64)\n- **Framework**: ${meta.stack.join(', ')}\n- **UI Layer**: Native Desktop\n`,
        'utf-8'
      );
    }
  }

  return projectVaultDir;
}
